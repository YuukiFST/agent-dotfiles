"""Write lib/black-hole-art.ts from a photo, on the 0xSero/ascii-art dot lattice.

usage:
  MIX=0 BLUR=2 python -P <ascii-art>/scripts/photo_dots.py hole.png map.txt 14 45 80
  GLOW=0.12 python -P scripts/black_hole_art.py hole.png map.txt <ascii-art>/assets/lattice.json lib/black-hole-art.ts [preview.png]

photo_dots.py decides each cell's glyph ('#' bright, '.' dim, ' ' empty); this script
adds '.' where the photo's red glow is brighter than GLOW, gives every glyph the
photo's color under it, and records the hole's center for the rotating shimmer.
"""
import json
import os
import sys

import numpy as np
from PIL import Image

image_path, map_path, lattice_path, out_path = sys.argv[1:5]
preview_path = sys.argv[5] if len(sys.argv) > 5 else None
glow = float(os.environ.get("GLOW", "0.12"))

lattice = json.load(open(lattice_path))
cell_w, cell_h = lattice["px"], lattice["py"]
lines = open(map_path).read().rstrip("\n").split("\n")
rows = len(lines)

# photo_dots.py resizes the image to rows * cell_h pixels tall; sample the same pixels.
photo = Image.open(image_path).convert("RGB")
scale = rows * cell_h / photo.height
photo = photo.resize((int(photo.width * scale), int(rows * cell_h)), Image.LANCZOS)
pixels = np.asarray(photo).astype(float)
cols = int(photo.width / cell_w)


def patch(row: int, col: int) -> np.ndarray:
    y = int((row + 0.5) * cell_h)
    x = int((col + 0.5) * cell_w)
    return pixels[max(0, y - 12) : y + 13, max(0, x - 7) : x + 8].reshape(-1, 3)


def cell_color(row: int, col: int) -> int:
    cells = patch(row, col)
    lum = cells.mean(1)
    # The brighter half of the patch, so thin streaks keep their color.
    top = cells[lum >= np.median(lum)].mean(0)
    boost = min(255.0 / max(top.max(), 1.0), 1.6)
    r, g, b = np.clip(top * boost, 0, 255).astype(int)
    return (int(r) << 16) | (int(g) << 8) | int(b)


glyphs: list[str] = []
colors: list[list[int]] = []
for row in range(rows):
    line = lines[row].ljust(cols)[:cols]
    text = ""
    row_colors = []
    for col, ch in enumerate(line):
        lum = patch(row, col).mean() / 255
        if ch == " " and lum > glow:
            ch = "."
        text += ch
        row_colors.append(cell_color(row, col) if ch != " " else 0)
    glyphs.append(text)
    colors.append(row_colors)

while glyphs and glyphs[0].strip() == "":
    glyphs.pop(0)
    colors.pop(0)
while glyphs and glyphs[-1].strip() == "":
    glyphs.pop()
    colors.pop()

# The hole is the largest run of empty cells that does not reach the border (empty
# space around the disk does); its centroid anchors the shimmer.
from scipy import ndimage

empty = np.array([[ch == " " for ch in text] for text in glyphs])
labels, count = ndimage.label(empty)
border = set(labels[0]) | set(labels[-1]) | set(labels[:, 0]) | set(labels[:, -1])
inner = [n for n in range(1, count + 1) if n not in border]
hole = max(inner, key=lambda n: int((labels == n).sum()))
center_row, center_col = (float(v) for v in ndimage.center_of_mass(labels == hole))

with open(out_path, "w", encoding="utf8", newline="\n") as out:
    out.write("// Generated by scripts/black_hole_art.py; regenerate with that script, do not edit.\n")
    out.write("// Glyphs come from 0xSero/ascii-art photo_dots.py (MIT, see THIRD_PARTY_NOTICES.md).\n\n")
    out.write(f"export const BLACK_HOLE_COLUMNS = {cols};\n")
    out.write(f"export const BLACK_HOLE_CENTER = {{ row: {center_row:.2f}, column: {center_col:.2f} }} as const;\n\n")
    out.write("/** One string per row; '#' bright, '.' dim, ' ' empty. */\n")
    out.write("export const BLACK_HOLE_GLYPHS: readonly string[] = [\n")
    for text in glyphs:
        out.write(f"  {json.dumps(text)},\n")
    out.write("];\n\n")
    out.write("/** The photo's color under each glyph as 0xRRGGBB; 0 where the row is empty. */\n")
    out.write("export const BLACK_HOLE_COLORS: readonly (readonly number[])[] = [\n")
    for row_colors in colors:
        out.write("  [" + ", ".join(f"0x{c:06x}" for c in row_colors) + "],\n")
    out.write("];\n")

print(cols, len(glyphs), f"center=({center_row:.2f},{center_col:.2f})")

if preview_path:
    from PIL import ImageDraw, ImageFont

    font = ImageFont.truetype("consola.ttf", 16)
    img = Image.new("RGB", (cols * 9 + 20, len(glyphs) * 18 + 20), (12, 12, 12))
    draw = ImageDraw.Draw(img)
    for r, text in enumerate(glyphs):
        for c, ch in enumerate(text):
            if ch != " ":
                color = colors[r][c]
                draw.text((10 + c * 9, 10 + r * 18), ch, fill=(color >> 16, (color >> 8) & 255, color & 255), font=font)
    img.save(preview_path)
